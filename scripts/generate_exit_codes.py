"""Generate bilingual exit-code documentation from the public registry."""

from __future__ import annotations

import argparse
import os
from pathlib import Path

from ddk.cli.contract import EXIT_CODES, exit_descriptions


def render(language: str) -> str:
    previous = os.environ.get("DDK_LANG")
    os.environ["DDK_LANG"] = language
    try:
        descriptions = exit_descriptions()
    finally:
        if previous is None:
            os.environ.pop("DDK_LANG", None)
        else:
            os.environ["DDK_LANG"] = previous
    title = "# 종료 코드" if language == "ko" else "# Exit codes"
    labels = "| 코드 | 분류 | 의미 |" if language == "ko" else "| Code | Category | Meaning |"
    lines = [
        title,
        "",
        "<!-- Generated by scripts/generate_exit_codes.py. -->",
        "",
        labels,
        "| --- | --- | --- |",
    ]
    lines.extend(
        f"| {code} | `{name}` | {descriptions[name]} |" for name, code in EXIT_CODES.items()
    )
    lines += [
        "",
        (
            '`--json`: `{"schema_version":"ddk/2","command":"...","status":"...",'
            '"data":{},"error":null,"actions":[]}`'
        ),
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1] / "docs"
    failures = []
    for lang, name in [("en", "EXIT-CODES.md"), ("ko", "EXIT-CODES.ko.md")]:
        path = root / name
        text = render(lang)
        if args.check:
            if not path.exists() or path.read_text() != text:
                failures.append(name)
        else:
            path.write_text(text)
    if failures:
        print("stale exit-code documents: " + ", ".join(failures))
    return bool(failures)


if __name__ == "__main__":
    raise SystemExit(main())
